# Registered tools that are not circuits, and circuits that cannot be chained yet.
NOT_CIRCUITS = {"resistors_approximation", "capacitors_approximation"}
STANDALONE = {"mosfet_current_mirror"}     # DC bias circuits with no signal input or output
NOT_CASCADABLE = {"binary_counter", "sipo_shift_register", "piso_shift_register"} | STANDALONE

_WAVE = {"1": "sine", "2": "square", "3": "triangle", "4": "sawtooth", "5": "pulse"}


def _generators() -> dict:
    return {f.__name__: f for f in CIRCUIT_TOOLS
            if f.__name__ not in NOT_CIRCUITS | {"cascade"}}


_SI = [(1e12, "T"), (1e9, "G"), (1e6, "M"), (1e3, "k"), (1, ""), (1e-3, "m"),
       (1e-6, "u"), (1e-9, "n"), (1e-12, "p")]


def _fnum(x) -> str:
    """Engineering notation (16000 -> 16k, 1e-7 -> 100n), no units."""
    try:
        v = float(x)
    except (TypeError, ValueError):
        return str(x)
    if v == 0 or not math.isfinite(v):
        return f"{v:g}"
    for scale, suffix in _SI:
        if abs(v) >= scale * 0.9999:
            return f"{v / scale:.4g}{suffix}"
    return f"{v:.4g}"


def _value(e) -> str | None:
    v = e.attr(e.type) if e.attrs is not None else (e.tail[0] if e.tail else None)
    return None if v is None else _fnum(v)


def _source_desc(e) -> str:
    if e.type == "170":
        return f"frequency sweep {_fnum(e.tail[0])}-{_fnum(e.tail[1])} Hz, {_fnum(e.tail[2])} V peak"
    wf = _WAVE.get(waveform(e), f"waveform {waveform(e)}")
    if e.attrs is not None:
        return f"{wf}, {_fnum(e.attr('maxv', '?'))} V"
    return f"{wf}, {_fnum(e.tail[1])} Hz, {_fnum(e.tail[2])} V peak"


def _node_desc(nl: Netlist, node, skip: set[int]) -> str:
    """What is attached to a port node (via wires): helps judge loading."""
    net_of = nets(nl.elements)
    here = net_of.get(node)
    parts = []
    for i, e in enumerate(nl.elements):
        if i in skip or e.type in ("w", "g", "O", "x"):
            continue
        ts = terminals(e)
        if ts is None:
            continue
        for ti, t in enumerate(ts):
            if net_of.get(t) == here:
                if e.type == "a":
                    parts.append("op-amp output (low impedance)" if ti == 2
                                 else "op-amp input pin")
                else:
                    v = _value(e)
                    parts.append(f"{e.type}={v}" if v else e.type)
    return ", ".join(parts) if parts else "no known elements (chip pins not visible)"


def _components(nl: Netlist) -> str:
    items = []
    for e in nl.elements:
        if e.type in ("r", "c", "l") and _value(e):
            items.append(f"{e.type}={_value(e)}")
        elif e.type == "a":
            if e.attrs is None and len(e.tail) >= 2:
                items.append(f"op-amp(+/-{_fnum(e.tail[0])} V limit)")
            else:
                items.append("op-amp")
    return ", ".join(items) if items else "(none listed)"


def _fact_sheet(stages: list[Stage], comp: Composite, analysis: Analysis) -> str:
    drv = next((e for e in comp.netlist.elements if is_signal_source(e)), None)
    out = [f"Cascaded {len(stages)} stages left to right ({comp.netlist.dialect} format), "
           "each joined to the next by a plain wire (no buffer).",
           "Chain is driven by: " + (_source_desc(drv) + " (stage 1's source)" if drv
                                      else "stage 1 itself (it is a generator)")]
    for k, s in enumerate(stages):
        skip = {i for i, e in enumerate(s.nl.elements) if is_signal_source(e)}
        arg_txt = ", ".join(f"{a}={v}" for a, v in s.args.items())
        line = [f"Stage {k + 1}: {s.name}({arg_txt})",
                f"  parts: {_components(s.nl)}"]
        srcs = [e for e in s.nl.elements if is_signal_source(e)]
        if srcs:
            keep = "kept - drives the whole chain" if k == 0 else "REMOVED (fed by previous stage)"
            line.append(f"  own source: {_source_desc(srcs[0])} -> {keep}")
        if s.ports.inputs:
            line.append("  input node touches: " + _node_desc(s.nl, s.ports.inputs[0].node, skip))
        if s.ports.outputs:
            line.append("  output node touches: " + _node_desc(s.nl, s.ports.outputs[0].node, skip))
        for w in s.warnings:
            line.append(f"  generator warning: {w}")
        if s.note:
            line.append(f"  generator note: {s.note}")
        out.extend(line)
    out.append(analysis.to_text())
    fixers = _fixers()
    out.append("Automatic fixes available through your tools: "
               + (", ".join(fixers) if fixers else
                  "NONE for loading - no buffer/follower circuit is registered yet. Do not offer "
                  "to add one; describe it as a change the user would make by hand or request later."))
    out.append("Not covered even by the computed block: op-amp bandwidth and slew, clipping inside "
               "the response curve (only the peak-versus-limit line checks it), component "
               "tolerances. Scope vertical scales after stage 1 were sized for each stage's own "
               "standalone source and may be off. Stage hint labels such as 'f.3db' were removed "
               "because they show unloaded values.")
    if comp.unverified:
        out.append("Structural check could not see inside: " + "; ".join(comp.unverified))
    return "\n".join(out)



class FactSheet(str):
    """The note for the model, carrying the code-written user reply as `.reply`."""
    reply: str = ""
    fix_call: tuple | None = None     # (tool name, arguments) that rebuilds the circuit with the offered buffer fix
    alt_call: tuple | None = None     # (tool name, arguments) that rebuilds it exactly as asked (no auto buffers)


def _gain_word(shape: str) -> str:
    """'peak gain' for a band-pass response (it is not flat), 'passband gain' otherwise."""
    return "peak gain" if "band-pass" in (shape or "") else "passband gain"


def _nice(v: float) -> float:
    """Smallest 1-2-5 value >= v."""
    e = 10 ** math.floor(math.log10(v))
    for m in (1, 2, 5, 10):
        if m * e >= v * 0.9999:
            return m * e
    return 10 * e


def _fix_scopes(comp: Composite, analysis: Analysis) -> None:
    _fix_scopes_nl(comp.netlist, analysis)


def _fix_scopes_nl(netlist: Netlist, analysis: Analysis) -> None:
    """Stage scopes were sized for each stage's own source. Resize every scope on an
    output marker from the computed peak at that node (about 2 divisions tall)."""
    if netlist.dialect != "legacy":
        return
    for sc in netlist.scopes:
        e = netlist.elements[sc.index]
        peak = analysis.node_peaks.get((e.x1, e.y1)) if e.type == "O" else None
        if peak and peak > 0 and len(sc.tail) >= 4:
            sc.tail[3] = f"{_nice(peak / 2.5):g}"


# Knobs that raise a stage's INPUT impedance without changing what it does
# (inverting_amp: the feedback resistor is gain * res, so the gain is kept).
FIX_KNOBS = {"inverting_amp": ("res", "input resistor", "gain")}
MAX_FEEDBACK_OHMS = 2e6        # beyond this the suggested fix is not a sensible design (noise, leakage)
_FEEDBACK = {"inverting_amp": lambda args, default: float(args.get("res", default("res")))
             * float(args.get("gain", default("gain")))}
_FIX_FACTORS = (2, 5, 10, 20, 50, 100)


def _default(fn_name: str, arg: str):
    p = inspect.signature(_generators()[fn_name]).parameters.get(arg)
    return None if p is None or p.default is inspect.Parameter.empty else p.default


def _fixers() -> list[str]:
    """Registered circuits that can isolate two stages (unity-gain buffers)."""
    # op-amp followers only: a transistor follower has a DC offset and is not a clean buffer
    return sorted(n for n in _generators()
                  if ("follower" in n or "buffer" in n) and "emitter" not in n and "source" not in n)


SEVERE_LOADING = 0.5          # below this (-6 dB) the circuit as asked is not what the user meant


def _severe(analysis: Analysis) -> bool:
    return bool(analysis.supported and analysis.loaded and analysis.worst_load is not None
                and analysis.worst_load < SEVERE_LOADING)


def _buffer_args(name: str, built: list[Stage] | None) -> dict:
    """Give an added buffer the same output limit as the op-amps already in the circuit
    (the smallest), so it never sets a higher or lower limit than the rest."""
    if not built:
        return {}
    lims = []
    for st in built:
        for e in st.nl.elements:
            if e.type == "a" and e.tail:
                try:
                    lims.append(abs(float(e.tail[0])))
                except ValueError:
                    pass
    if not lims:
        return {}
    try:
        p = inspect.signature(_generators()[name]).parameters.get("amp_supply")
    except (KeyError, ValueError, TypeError):
        return {}
    lim = min(lims)
    return {"amp_supply": lim} if p is not None and p.default != lim else {}


HEADROOM_TARGET = 0.5         # the fix lowers the biggest op-amp peak to this share of its limit


def _nice_down(v: float) -> float:
    """Largest 1-2-5 value <= v."""
    e = 10.0 ** math.floor(math.log10(v))
    for m in (5, 2, 1):
        if m * e <= v * 1.0001:
            return m * e
    return e


def _flag_kind(flag: str) -> str:
    return flag.split(":")[0]


def _find_headroom_fix(analysis: Analysis, rebuild):
    """Lower the driving source so every op-amp peaks at about half its limit. `rebuild(amp)` returns
    the analysis of the same circuit with that source amplitude. Kept only if the headroom/clipping
    flags are really gone and nothing new is flagged. Returns (new amplitude, new analysis) or None."""
    if not analysis.supported or not analysis.headroom or not analysis.source_amp:
        return None
    scale = min(HEADROOM_TARGET * lim / peak for peak, lim in analysis.headroom)
    if scale >= 1:
        return None
    new = _nice_down(analysis.source_amp * scale)
    try:
        a2 = rebuild(new)
    except ValueError:
        return None
    if not a2.supported or a2.headroom:
        return None
    if {_flag_kind(f) for f in a2.flags} - {_flag_kind(f) for f in analysis.flags}:
        return None
    return new, a2


def _headroom_text(analysis: Analysis, new: float, a2: Analysis) -> list[str]:
    peak = max(p for p, _ in analysis.headroom) * new / analysis.source_amp
    lim = min(l for _, l in analysis.headroom)
    what = "clipping" if any(p > l for p, l in analysis.headroom) else "headroom"
    return ["", f"**Fix for the {what}:** lower the source from {fmt(analysis.source_amp, 'V')} to "
            f"{fmt(new, 'V')}. I rebuilt the circuit with that: the biggest op-amp peak drops to about "
            f"{fmt(peak, 'V')} of its +/-{fmt(lim, 'V')} limit and "
            + ("code still reports: " + " ".join(a2.flags) if a2.flags else "nothing else is flagged")
            + ". The shape of the response doesn't change, only its size.",
            f"To build it, ask for the same circuit with a {fmt(new, 'V')} source amplitude, or just say "
            "\"apply the fix\"."]


def _find_buffer_fix(stages: list[dict], analysis: Analysis, built: list[Stage] | None = None):
    """Insert a registered buffer at each loaded junction (first loaded junction, rebuild,
    repeat; at most 3) and keep the result only if the loading is really gone.
    Returns (buffer name, [(stage before, stage after)], new stage list, analysis) or None."""
    fixers = _fixers()
    if not fixers or not analysis.loaded:
        return None
    name, trial, a, where = fixers[0], [dict(x) for x in stages], analysis, []
    bargs = _buffer_args(name, built)
    for _ in range(3):
        if not a.loaded:
            break
        k = a.loaded[0]                          # junction k joins trial[k-1] and trial[k]
        where.append((trial[k - 1]["circuit"], trial[k]["circuit"]))
        trial.insert(k, {"circuit": name, "args": dict(bargs)})
        try:
            _, _, a = _build(trial, analysis.source_amp)
        except ValueError:
            return None
        if not a.supported:
            return None
    if a.loaded:
        return None
    return name, where, trial, a


def _find_fix(stages: list[dict], built: list[Stage], analysis: Analysis):
    """For the first loaded junction, raise the loading stage's input resistance until the
    loading flag clears (checked by rebuilding and re-analysing), then scale that stage's
    gain setting so the chain gain returns to the product of the stages' own gains.
    Returns (stage no, label, arg, old, new, gain_arg, old_gain, new_gain, analysis) or None."""
    if not analysis.loaded:
        return None
    k = analysis.loaded[0]                      # junction k: stage k+1 loads stage k
    spec = stages[k]
    knob = FIX_KNOBS.get(spec["circuit"])
    if not knob:
        return None
    arg, label, garg = knob
    args = dict(spec.get("args") or {})
    cur = args.get(arg, _default(spec["circuit"], arg))
    g0 = args.get(garg, _default(spec["circuit"], garg))
    if cur is None or g0 is None:
        return None
    for f in _FIX_FACTORS:
        trial = [dict(x) for x in stages]
        trial[k] = {"circuit": spec["circuit"], "args": {**args, arg: float(cur) * f, garg: float(g0)}}
        try:
            _, _, a2 = _build(trial, analysis.source_amp)
        except ValueError:
            return None
        if not (a2.supported and k not in a2.loaded):
            continue
        g1 = float(g0)
        if analysis.expected_gain and a2.gain:        # chain gain is linear in this stage's gain
            g1 = float(g0) * analysis.expected_gain / a2.gain
            trial[k]["args"][garg] = g1
            try:
                _, _, a3 = _build(trial, analysis.source_amp)
            except ValueError:
                a3 = None
            if a3 is not None and a3.supported and k not in a3.loaded:
                a2 = a3
            else:
                g1 = float(g0)
        rf = float(cur) * f * g1                         # the feedback resistor this fix would need
        if spec["circuit"] in _FEEDBACK and rf > MAX_FEEDBACK_OHMS:
            return ("impractical", k + 1, label, float(cur) * f, rf)
        return (k + 1, label, arg, float(cur), float(cur) * f, garg, float(g0), g1, a2)
    return None


def _special_text(analysis: Analysis) -> list[str]:
    """Reply paragraphs for chains with a comparator (Schmitt trigger) or a DAC at the start."""
    c, st = analysis.comparator, analysis.static
    if c:
        txt = (f"Stage {c['stage']} is a {_pretty(c['name'])}, a comparator with hysteresis: instead of "
               f"amplifying, it switches its output between +/-{fmt(c['limit'], 'V')}, so there is no gain or "
               f"frequency response to quote. Its trip points are {c['utp']:.3g} V (upper) and "
               f"{c['ltp']:.3g} V (lower), a hysteresis of {c['utp'] - c['ltp']:.3g} V. The signal reaching it "
               f"swings from {c['swing_lo']:.3g} V to {c['swing_hi']:.3g} V")
        txt += (", so it crosses both trip points and the output will toggle." if c["toggles"]
                else ", which is not enough, as noted below.")
        return [txt]
    txt = (f"Stage 1 is a {_pretty(st['dac'])}, which makes its own levels and has no signal input. At code "
           f"{st['code']} it outputs {st['v_dac']:.4g} V DC, and since everything after it is linear the DC level "
           f"at the end of the chain is {st['v_end']:.4g} V. I haven't computed a frequency response: the DAC only "
           "changes when you change its code, and how the later stages smooth a changing code is not modelled.")
    return [txt]


def _render_reply(stages: list[dict], built: list[Stage], comp: Composite, analysis: Analysis,
                  fixout: dict | None = None) -> str:
    """Code-written chat reply for a cascade, built from computed facts. No model prose."""
    drv = next((e for e in comp.netlist.elements if is_signal_source(e)), None)
    chain = " \u2192 ".join(f"{_pretty(s.name)}{_args_txt(s.args)}" for s in built)
    out = [f"I've chained them into one circuit: **{chain}**. The stages are joined by plain wires "
           + ("and driven by " + _source_phrase(drv) + " (stage 1's source)." if drv
              else "and stage 1 is itself a generator.")]
    notes = [f"One thing to know ({_pretty(s_.name)}): {w}." for s_ in built for w in s_.warnings]
    out.append("")
    if analysis.supported and analysis.oscillator:
        o = analysis.oscillator
        supply = o["shape"] in ("rectified", "dc_ripple")
        levels = (f"a swing of {fmt(o['v_low'], 'V')} to {fmt(o['v_high'], 'V')}, high for {o['duty']:.1%} of each period"
                  if o["shape"] == "square" else
                  f"a level between {fmt(o['v_low'], 'V')} and {fmt(o['v_high'], 'V')}" if supply
                  else f"peaks of +/-{fmt(o['v_peak'], 'V')}")
        what = ("makes its own supply" if supply else "makes its own signal" if not o.get("intro") else
                "switches its own drive source between its rails, so it doesn't amplify")
        shape_txt = "ripple" if supply else f"{o['shape']} wave"
        txt = (f"Stage 1 is {_a(_pretty(o['name']))}, which {what}: a {shape_txt} at about "
               f"{fmt(o['f0'], 'Hz')}, {levels}"
               + (" (an estimate: see below)" if o["approximate"] else "")
               + f". At that frequency the whole chain has a gain of {o['gain']:.3g}, so a linear model puts the output "
               f"at {o['out_lo']:.3g} V to {o['out_hi']:.3g} V in steady state"
               + (", which a real stage cannot reach: see the clipping warnings below" if o.get("clips") else ""))
        txt += (f", and its harmonic content is about {o['thd'] * 100:.2g}% of the fundamental." if o["shape"] != "sine"
                else ".")
        out += [txt, ""]
        out += [f"Note: {n[0].upper() + n[1:]}." for n in o["notes"]] + [""]
    if analysis.supported and analysis.adc:
        a = analysis.adc
        txt = (f"Stage {len(built)} is a {a['bits']}-bit flash ADC with a {fmt(a['vref'], 'V')} reference: one step is "
               f"{fmt(a['lsb'], 'V')}. The signal reaching it swings {a['lo']:.3g} V to {a['hi']:.3g} V, which reads "
               f"as codes {a['code_lo']} to {a['code_hi']} out of 0 to {2 ** a['bits'] - 1}"
               + (", and part of that is outside its range (see the clipping warning below)." if a["clips"]
                  else "."))
        out += [txt, ""]
    if analysis.supported and analysis.regulator:
        r = analysis.regulator
        txt = (f"Stage 1 is a linear regulator: with {fmt(r['vin'], 'V')} in it holds its output at "
               f"{r['vout']:.4g} V. The {fmt(r['ripple_in'], 'V')} of {fmt(r['f_ripple'], 'Hz')} ripple on its input "
               f"comes out as {fmt(r['ripple_out'], 'V')} (a factor of {r['ripple_gain']:.3g}, "
               f"{-20 * math.log10(max(r['ripple_gain'], 1e-12)):.0f} dB of rejection), and a slow change in the "
               f"input moves the output by {r['line_reg_mv_per_v']:.3g} mV per volt.")
        if r["load_reg_mv"] is not None and r["i_load"]:
            txt += (f" Taking the load from {fmt(r['i_load'] / 10, 'A')} up to {fmt(r['i_load'], 'A')} changes the "
                    f"output by {abs(r['load_reg_mv']):.3g} mV.")
        out += [txt, ""]
    if analysis.oneshot:
        o = analysis.oneshot
        out += [f"Stage 1 is a 555 one-shot: each trigger makes its output go to {fmt(o['vcc'], 'V')} for "
                f"{fmt(o['width'], 's')} (1.1RC) and then return to 0 V. A one-shot has no repeating signal, so I "
                "have not solved the chain's steady state; only the pulse is described."
                + (f" The rest of the chain has a gain of {o['gain']:.3g} at {fmt(o['f_eq'], 'Hz')}, the pulse's own "
                   "rate, which is a rough guide to how much of the pulse gets through." if o["gain"] is not None
                   else ""), ""]
        if analysis.flags:
            out += ["**Worth knowing:**"] + ["- " + f for f in analysis.flags]
    elif not analysis.supported and (analysis.comparator or analysis.static):
        out += _special_text(analysis)
        if analysis.flags:
            out += ["", "**Worth knowing:**"] + ["- " + f for f in analysis.flags]
    elif not analysis.supported:
        out.append(f"I built it and checked the wiring, but its response couldn't be computed "
                   f"({analysis.reason}), so I can't say how it behaves.")
    elif analysis.adc and analysis.gain is None:               # a generator straight into the ADC: nothing to quote a gain for
        out += ["**Worth knowing:**"] + ["- " + f for f in analysis.flags] if analysis.flags else \
            ["I found nothing worth flagging: the signal fits the converter's range."]
    elif any(f.startswith("Crossover") for f in analysis.flags):
        out.append("I can't give a meaningful small-signal gain here: the output transistors are off at rest, so a "
                   "linear model around that point gives almost nothing, while the real stage passes signals "
                   "larger than about 0.6 V with that much taken off each peak.")
        out += ["", "**Worth knowing:**"] + ["- " + f for f in analysis.flags]
    else:
        if analysis.sloping:
            out.append("Overall its gain changes steadily with frequency (integrator or "
                       "differentiator behaviour), so there is no single gain or cutoff to quote.")
        else:
            txt = (f"Overall it's {_a(analysis.shape)} circuit with a {_gain_word(analysis.shape)} of about "
                   f"{analysis.gain:.3g}")
            txt += _tail(analysis)
            out.append(txt + ".")
        if analysis.flags:
            out += ["", "**Worth knowing:**"] + ["- " + f for f in analysis.flags]
        else:
            out.append("I found nothing worth flagging: no loading, corner shift or clipping.")
        bfix = _find_buffer_fix(stages, analysis, built)
        if analysis.loaded and analysis.whatif and not _fixers():
            g, lo, hi = analysis.whatif
            out += ["", f"If each junction had an ideal unity-gain buffer, the chain would give a gain of "
                    f"about {g:.3g} and {_band_phrase(lo, hi, True)}. I can't add a buffer for you, though: "
                    "no buffer circuit is registered yet."]
        if bfix:
            name, where, trial, a2 = bfix
            spots = _join([f"the {_pretty(x)} and the {_pretty(y)}" for x, y in where])
            bits = [f"a gain of about {a2.gain:.3g}"] if a2.gain is not None else []
            if a2.lo:
                bits.append(f"a lower corner of {fmt(a2.lo, 'Hz')}")
            if a2.hi:
                bits.append(f"an upper corner of {fmt(a2.hi, 'Hz')}")
            ask = ", then ".join(_pretty(t["circuit"]) + _args_txt(t.get("args") or {}) for t in trial)
            out += ["", f"**Fix with a buffer:** I rebuilt the chain with a {_pretty(name)} between {spots}. "
                    "The loading goes away" + _gives(bits) + "."]
            out.append("After that change, " + ("code still reports: " + " ".join(a2.flags)
                                                 if a2.flags else "nothing else is flagged."))
            out.append(f"To build it, ask for: {ask}. Or just say \"apply the buffer fix\".")
            if fixout is not None:
                fixout["call"] = ("cascade", {"stages": trial})
        fix = _find_fix(stages, built, analysis)
        if fix and fix[0] == "impractical":
            if not bfix:
                _, n, label, new_res, rf = fix
                out += ["", f"Changing stage {n}'s resistors can't fix this sensibly: the loading only clears "
                        f"with {_a(label)} around {_fnum(new_res)}\u03a9 and a feedback resistor of about "
                        f"{_fnum(rf)}\u03a9, which is impractical (noise and leakage). The stage before it "
                        "has too high an output resistance for this amplifier."]
        elif fix:
            n, label, arg, cur, new, garg, g0, g1, a2 = fix
            bits = [f"a gain of about {a2.gain:.3g}"] if a2.gain is not None else []
            if a2.lo:
                bits.append(f"a lower corner of {fmt(a2.lo, 'Hz')}")
            if a2.hi:
                bits.append(f"an upper corner of {fmt(a2.hi, 'Hz')}")
            gtxt = (f" and set `{garg}` from {_fnum(g0)} to {_fnum(g1)} to bring the chain gain toward "
                    f"{analysis.expected_gain:.3g}" if abs(g1 / g0 - 1) > 0.005 else "")
            lead = "**Or, without adding a stage:**" if bfix else "**A fix you can make now:**"
            out += ["", f"{lead} raise stage {n}'s {label} (`{arg}`) from {_fnum(cur)} to "
                    f"{_fnum(new)}{gtxt}. I rebuilt the circuit with that change: the loading goes away "
                    "and" + (_gives(bits)[4:] if bits else " nothing else needs changing") + "."]
            out.append("After that change, " + ("code still reports: " + " ".join(a2.flags)
                                                 if a2.flags else "nothing else is flagged."))
        elif analysis.loaded and not bfix:
            out += ["", "There's no automatic fix for this loading with the circuits available."]
        if not analysis.loaded:
            hf = _find_headroom_fix(analysis, lambda amp: _build(stages, amp)[2])
            if hf:
                out += _headroom_text(analysis, hf[0], hf[1])
                if fixout is not None:
                    fixout["call"] = ("cascade", {"stages": stages, "source_amplitude": hf[0]})
    out += ([""] + notes) if notes else []
    out += ["", "_Not modelled: op-amp bandwidth and slew, tolerances. Output scopes were rescaled "
            "from the computed peaks. Written by code, not by the language model._"]
    return "\n".join(out)


