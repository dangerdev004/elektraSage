def _signature_line(fn) -> str:
    """e.g. inverting_amp: REQUIRED gain, res; optional (have defaults): amp_supply=50.0, ..."""
    req, opt = [], []
    for p in inspect.signature(fn).parameters.values():
        (req if p.default is inspect.Parameter.empty else opt).append(
            p.name if p.default is inspect.Parameter.empty else f"{p.name}={p.default}")
    return (f"{fn.__name__}: REQUIRED {', '.join(req) or 'nothing'}"
            + (f"; optional (have defaults): {', '.join(opt)}" if opt else ""))


