"""The `cascade` tool the LLM calls.

The LLM only chooses WHICH registered circuits to chain, in WHAT ORDER, and
with WHAT parameters (all taken from the user's request). Every circuit is
generated by the existing deterministic generator functions; this module only
lifts, places and wires their output.

It returns (netlist, note). The netlist goes to the user; the note is a short
fact sheet the model reads so it can judge whether the chain makes electrical
sense (loading, headroom, passband) - the one thing code here cannot verify.
"""

